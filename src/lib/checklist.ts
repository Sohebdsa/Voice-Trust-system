/**
 * PRD §4 (A1–A11) field checklist. `key` is the domain-type property that holds
 * the field; `null` means the model has no home for it yet. Kept as plain data
 * so the audit screen can diff the PRD against `src/lib/data/types.ts` without
 * a DB.
 */
export type ChecklistField = {
  /** PRD field name, verbatim. */
  name: string;
  /** Property on the domain type, or null when missing. */
  key: string | null;
  /** How a count/relation stands in for the field, or why it is absent. */
  note?: string;
};

export type ChecklistTable = {
  id: string;
  title: string;
  type: string;
  fields: ChecklistField[];
};

const f = (name: string, key: string | null, note?: string): ChecklistField => ({ name, key, note });

